test('failed grading can be retried without losing the typed answer', async ({ page, app }) => {
  const content = { ...assessment, exercises: [assessment.exercises[1]] }
  await app.seed(learningState(content))
  // This is an assessment, so it may contain only one independent question.
  const saved = await app.saved()
  saved.plan!.modules[0].lessons[0].kind = 'test'
  await app.seed(saved)
  await app.ai({ gradeOpen: { error: 'E2E grading unavailable' } })
  await page.goto('/lesson/first')
  await page.getByRole('button', { name: 'Start assessment' }).click()
  await page.getByLabel('Your answer', { exact: true }).fill('The caller receives the function result.')
  await page.getByRole('button', { name: 'Check', exact: true }).click()
  await expect(page.getByText('E2E grading unavailable', { exact: true })).toBeVisible()
  await app.ai({})
  await page.getByRole('button', { name: 'Try again', exact: true }).click()
  await expect(page.getByLabel('Your answer', { exact: true })).toHaveValue('The caller receives the function result.')
  await page.getByRole('button', { name: 'Check', exact: true }).click()
  await expect(page.getByText('10 / 10', { exact: true })).toBeVisible()
  await expect.poll(async () => (await app.saved()).stats.history.length).toBe(1)
})

test('lesson generation error offers regeneration and validates real browser tests', async ({ page, app }) => {
  const saved = learningState(lesson)
  saved.lessons = {}
  await app.seed(saved)
  await app.ai({ lesson: { error: 'E2E lesson unavailable' } })
  await page.goto('/lesson/first')
  await expect(page.getByText('E2E lesson unavailable', { exact: true })).toBeVisible()
  await app.ai({})
  await page.getByRole('button', { name: /Try again|Regenerate/ }).click()
  await expect(page.getByRole('button', { name: 'Start learning', exact: true })).toBeVisible()
  await expect.poll(async () => (await app.saved()).lessons.first?.exercises.filter((e) => e.type === 'code').every((e) => e.testsStatus === 'verified')).toBe(true)
})

