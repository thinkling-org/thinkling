test('leaving an answered lesson requires confirmation and preserves mistake cards', async ({ page, app }) => {
  await app.seed(learningState())
  await page.goto('/lesson/first')
  await page.getByRole('button', { name: 'Start assessment' }).click()
  await page.getByRole('radio', { name: /3/ }).click()
  await page.getByRole('button', { name: 'Check', exact: true }).click()
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.getByRole('button', { name: 'Close lesson' }).click()
  await expect(page).toHaveURL(/\/lesson\/first$/)
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Close lesson' }).click()
  await expect(page).toHaveURL(/\/path$/)
  await expect.poll(async () => (await app.saved()).flashcards.length).toBe(1)
  expect((await app.saved()).plan!.modules[0].lessons[0].status).toBe('current')
})
