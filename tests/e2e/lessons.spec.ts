async function editCode(page: Page, code: string) {
  const editor = page.getByRole('textbox', { name: 'Editor content', exact: true })
  await editor.focus()
  // Monaco uses the browser UA for shortcuts; Desktop Safari emulates macOS,
  // even when Playwright itself runs on Windows or Linux.
  const mac = await page.evaluate(() => navigator.userAgent.includes('Macintosh'))
  await page.keyboard.press(mac ? 'Meta+A' : 'Control+A')
  await page.keyboard.insertText(code)
}

test('finishes an assessment using choice, open answer and real Monaco worker execution', async ({ page, app }) => {
  await app.seed(learningState())
  await page.goto('/path')
  await page.getByRole('button', { name: /Returning values, current/ }).click()
  await page.getByRole('button', { name: 'Start +20 XP' }).click()
  await page.getByRole('button', { name: 'Start assessment' }).click()
  await expect(page.getByRole('button', { name: 'Check', exact: true })).toBeDisabled()
  await page.getByRole('radio', { name: /6/ }).click()
  await page.getByRole('button', { name: 'Check', exact: true }).click()
  await expect(page.getByText('Great work!', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByLabel('Your answer', { exact: true }).fill('A function sends its result back to its caller.')
  await page.getByLabel('Your answer', { exact: true }).press('Control+Enter')
  await expect(page.getByText('10 / 10', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await editCode(page, 'function double(value) { return value * 2; }')
  await page.getByRole('button', { name: /Run tests/ }).click()
  await expect(page.getByRole('tab', { name: 'Tests 2/2', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Check with Claude', exact: true }).click()
  await expect(page.getByText('Great work!', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Lesson complete!' })).toBeVisible()
  await expect.poll(async () => (await app.saved()).plan!.modules[0].lessons[0].status).toBe('done')
  const saved = await app.saved()
  expect(saved.plan!.modules[0].lessons[1].status).toBe('current')
  expect(saved.stats.xp).toBeGreaterThanOrEqual(60)
  expect(saved.stats.history).toHaveLength(3)
  expect(saved.flashcards).toHaveLength(1)
  await page.getByRole('link', { name: 'Continue', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: /Returning values, completed/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /Function assessment, current/ })).toBeVisible()
})

